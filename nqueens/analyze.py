"""Audit raw solutions and generate report tables, figures and numbers.

Every number quoted in the report text comes from ``report/numbers.tex``,
which defines ``\\res{key}`` values; an unknown key stops LaTeX with an error.
"""
import argparse
from collections import defaultdict,Counter
import csv
import json
from pathlib import Path
from statistics import mean,median
from .board import check_solution
from .sat_model import clauses


def read_results(directory):
    rows = []
    for path in sorted(Path(directory).glob("*.csv")):
        with path.open(newline="",encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                row["experiment"] = path.stem
                for key in ("n","repeat","seed"):
                    row[key] = int(row[key])
                for key in ("budget","process_time","build_time","solve_time","total_time"):
                    row[key] = float(row[key]) if row[key] else None
                rows.append(row)
    return rows


def audit(directory,rows):
    checked = 0
    raw = {}
    for path in sorted(Path(directory).glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            result = json.loads(line)
            key = (path.stem,result["n"],result["method"],result["repeat"])
            if key in raw:
                raise ValueError(f"duplicate raw result: {key}")
            raw[key] = result
            if result["status"] == "SAT":
                if not check_solution(result["n"],result["solution"]):
                    raise ValueError(f"invalid solution: {key}")
                checked += 1
            elif result["status"] == "UNSAT" and result["n"] not in (2,3):
                raise ValueError(f"unexpected UNSAT on ordinary N-queens: {key}")
    seen = set()
    for row in rows:
        key = (row["experiment"],row["n"],row["method"],row["repeat"])
        if key in seen or key not in raw or raw[key]["status"] != row["status"]:
            raise ValueError(f"CSV/raw mismatch: {key}")
        seen.add(key)
    if seen != set(raw):
        raise ValueError("CSV/raw record counts differ")
    for path in Path(directory).glob("*.config.json"):
        config = json.loads(path.read_text())
        expected = {(config["experiment"],n,m,r) for n in config["sizes"]
                    for m in config["methods"] for r in range(1,config["repeats"]+1)}
        actual = {key for key in seen if key[0] == config["experiment"]}
        if actual != expected:
            raise ValueError(f"incomplete experiment: {path.stem}")
    return dict(runs=len(rows),checked_solutions=checked,statuses=dict(Counter(r["status"] for r in rows)))


def solved(row):
    return row["status"] in ("SAT","UNSAT")


def par2(rows):
    return mean(row["process_time"] if solved(row) else 2*row["budget"] for row in rows)


def label(method):
    if method.startswith("sat:"):
        _,solver,amo,variant = method.split(":")
        return f"{amo}/{variant}"
    return {"cplex_cp":"CPLEX CP","cplex_mip":"CPLEX MIP","gurobi":"Gurobi","cpsat":"CP-SAT"}[method]


def key(method):
    """Short identifier used in ``\\res`` keys."""
    if method.startswith("sat:"):
        _,solver,amo,variant = method.split(":")
        return f"{solver}-{amo}-{variant}"
    return method.replace("_","-")


def latex_table(path,headers,body,alignment=None):
    alignment = alignment or "l"+"r"*(len(headers)-1)
    lines = [r"\begin{tabular}{"+alignment+"}",r"\toprule"," & ".join(headers)+r" \\",r"\midrule"]
    lines += [" & ".join(map(str,row))+r" \\" for row in body]
    lines += [r"\bottomrule",r"\end{tabular}"]
    path.write_text("\n".join(lines)+"\n",encoding="utf-8")


def fmt(seconds):
    return f"{seconds:.2f}" if seconds < 100 else f"{seconds:.1f}"


def measured_cell(rows,field="process_time"):
    done = [r for r in rows if solved(r)]
    if len(done) != len(rows):
        if not done:
            return "TO"
        return f"TO ({len(done)}/{len(rows)})"
    return fmt(median(r[field] for r in done))


def exact_name(method):
    return "SAT" if method.startswith("sat:") else label(method)


def write_numbers(path,values):
    lines = [r"% Generated by nqueens.analyze and nqueens.report_details; do not edit.",
             r"\makeatletter",
             r"\providecommand{\res}[1]{\ifcsname res@#1\endcsname\csname res@#1\endcsname"
             r"\else\PackageError{numbers}{Unknown result key #1}{}\fi}"]
    lines += [rf"\@namedef{{res@{k}}}{{{v}}}" for k,v in sorted(values.items())]
    lines += [r"\makeatother"]
    path.write_text("\n".join(lines)+"\n",encoding="utf-8")


def load_numbers(path):
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith(r"\@namedef{res@"):
                k,v = line[len(r"\@namedef{res@"):].split("}{",1)
                values[k] = v[:-1]
    return values


def update_numbers(path,new):
    values = load_numbers(path)
    values.update(new)
    write_numbers(path,values)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results",default="results")
    parser.add_argument("--report",default="report")
    args = parser.parse_args()
    rows = read_results(args.results)
    audit_result = audit(args.results,rows)
    report = Path(args.report)
    tables,figures = report/"tables",report/"figs"
    tables.mkdir(parents=True,exist_ok=True)
    figures.mkdir(parents=True,exist_ok=True)
    groups = defaultdict(list)
    for row in rows:
        groups[(row["experiment"],row["method"])].append(row)
    budgets = {r["budget"] for r in rows}
    if len(budgets) != 1:
        raise ValueError(f"experiments use different time limits: {budgets}")
    budget = budgets.pop()
    numbers = dict(budget=f"{budget:g}",par2penalty=f"{2*budget:g}",runs=str(audit_result["runs"]),
                   checked=str(audit_result["checked_solutions"]),
                   timeouts=str(audit_result["statuses"].get("TIMEOUT",0)),
                   errors=str(audit_result["statuses"].get("ERROR",0)))
    for (exp,method),values in groups.items():
        base = f"{exp}/{key(method)}"
        numbers[f"{base}/solved"] = f"{sum(map(solved,values))}/{len(values)}"
        numbers[f"{base}/par2"] = fmt(par2(values))
        for n in sorted({r["n"] for r in values}):
            cell = [r for r in values if r["n"] == n]
            numbers[f"{base}/{n}/time"] = measured_cell(cell)
            numbers[f"{base}/{n}/core"] = measured_cell(cell,"total_time")
            numbers[f"{base}/{n}/solved"] = f"{sum(map(solved,cell))}/{len(cell)}"

    encodings = {method:values for (exp,method),values in groups.items() if exp == "encodings"}
    ranking = sorted(encodings,key=lambda m:par2(encodings[m]))
    numbers["encodings/best"] = label(ranking[0])
    max_n = max(r["n"] for r in rows if r["experiment"] == "encodings")
    numbers["encodings/maxn"] = str(max_n)
    body,sizes = [],{}
    for method in ranking:
        values = encodings[method]
        _,_,amo,variant = method.split(":")
        top,count = max_n*max_n,0
        for clause,top in clauses(max_n,amo,variant):
            count += 1
        sizes[method] = dict(n_vars=top,n_constraints=count)
        numbers[f"encodings/{key(method)}/vars"] = f"{top:,}"
        numbers[f"encodings/{key(method)}/clauses"] = f"{count:,}"
        body.append([label(method),f"{sum(map(solved,values))}/{len(values)}",
                     fmt(par2(values)),f"{top:,}",f"{count:,}"])
    latex_table(tables/"encodings.tex",["Encoding / formulation","Solved","PAR-2 (s)","Variables","Clauses"],body)

    exact = [r for r in rows if r["experiment"] in ("exact","scaling")]
    methods = list(dict.fromkeys(r["method"] for r in exact))
    exact_sizes = sorted({r["n"] for r in exact})
    headers = ["$n$"]+[exact_name(m) for m in methods]
    for field,name in (("process_time","exact"),("total_time","exact_core")):
        body = [[n]+[measured_cell([r for r in exact if r["n"] == n and r["method"] == m],field) for m in methods]
                for n in exact_sizes]
        body.append(["Solved"]+[f"{sum(solved(r) for r in exact if r['method']==m)}/"
                                f"{sum(r['method']==m for r in exact)}" for m in methods])
        body.append(["PAR-2"]+[fmt(par2([r for r in exact if r["method"]==m])) for m in methods])
        latex_table(tables/f"{name}.tex",headers,body)
    for m in methods:
        values = [r for r in exact if r["method"] == m]
        numbers[f"all/{key(m)}/solved"] = f"{sum(map(solved,values))}/{len(values)}"
        numbers[f"all/{key(m)}/par2"] = fmt(par2(values))
    numbers["exact/maxn"] = str(max(exact_sizes))
    numbers["exact/runs"] = str(sum(r["method"] == methods[0] for r in exact))

    sat_methods = [m for (exp,m) in groups if exp == "solvers"]
    solver_sizes = sorted({r["n"] for r in rows if r["experiment"] == "solvers"})
    body = [[n]+[measured_cell([r for r in groups[("solvers",m)] if r["n"] == n]) for m in sat_methods]
            for n in solver_sizes]
    body.append(["Solved"]+[f"{sum(map(solved,groups[('solvers',m)]))}/{len(groups[('solvers',m)])}"
                            for m in sat_methods])
    body.append(["PAR-2"]+[fmt(par2(groups[("solvers",m)])) for m in sat_methods])
    names = dict(cadical195="CaDiCaL",glucose42="Glucose",minisat22="MiniSat",maplechrono="MapleChrono")
    latex_table(tables/"solvers.tex",["$n$"]+[names[m.split(":")[1]] for m in sat_methods],body)

    summary = audit_result | dict(time_limit=budget,
        encoding_ranking=[dict(method=m,par2=par2(encodings[m])) for m in ranking],
        encoding_sizes=sizes,exact={m:dict(solved=sum(solved(r) for r in exact if r["method"]==m),
            runs=sum(r["method"]==m for r in exact),par2=par2([r for r in exact if r["method"]==m])) for m in methods})
    (Path(args.results)/"summary.json").write_text(json.dumps(summary,indent=2),encoding="utf-8")
    update_numbers(report/"numbers.tex",numbers)

    # Figures show deadline penalties, rather than omitting failed runs.
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size":10,"axes.spines.top":False,"axes.spines.right":False,"figure.dpi":160})
    fig,ax = plt.subplots(figsize=(7.2,4.2))
    for method in ranking:
        values = encodings[method]
        ns = sorted({r["n"] for r in values})
        style = "-" if method.endswith("minimal") else "--"
        ax.plot(ns,[par2([r for r in values if r["n"]==n]) for n in ns],style,marker="o",ms=3,label=label(method))
    ax.set(xlabel="Board side n",ylabel="PAR-2 process time (s)",xscale="log",yscale="log")
    ax.set_xticks(ns,[str(n) for n in ns])
    ax.minorticks_off()
    ax.legend(fontsize=7,ncol=2)
    ax.grid(alpha=.2)
    fig.tight_layout()
    fig.savefig(figures/"encodings.png")
    plt.close(fig)
    fig,axes = plt.subplots(1,2,figsize=(9.0,3.8))
    for method in methods:
        values = [r for r in exact if r["method"]==method]
        axes[0].plot(exact_sizes,[par2([r for r in values if r["n"]==n]) for n in exact_sizes],marker="o",ms=3,
                     label=exact_name(method))
        times = sorted(r["process_time"] for r in values if solved(r))
        axes[1].step(times,range(1,len(times)+1),where="post",label=exact_name(method))
    axes[0].set(xlabel="Board side n",ylabel="PAR-2 process time (s)",xscale="log",yscale="log")
    axes[0].set_xticks(exact_sizes,[str(n) for n in exact_sizes])
    axes[0].minorticks_off()
    axes[1].set(xlabel="Process time (s)",ylabel="Solved runs (cumulative)",xscale="log")
    for ax in axes:
        ax.grid(alpha=.2)
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(figures/"exact.png")
    plt.close(fig)
    # Visual example comes from a measured solution, not a hand-drawn placement.
    example = next(json.loads(line) for line in (Path(args.results)/"encodings.jsonl").read_text().splitlines()
                   if json.loads(line)["n"]==8 and json.loads(line)["status"]=="SAT")
    fig,ax = plt.subplots(figsize=(3.4,3.4))
    from matplotlib.colors import ListedColormap
    ax.imshow([[(r+c)%2 for c in range(8)] for r in range(8)],cmap=ListedColormap(["#f1f4f7","#9cb2c6"]),vmin=0,vmax=1)
    ax.scatter(example["solution"],range(8),c="#182c42",s=180,marker="o",edgecolors="white",linewidths=1.8)
    ax.set_xticks(range(8),range(1,9))
    ax.set_yticks(range(8),range(1,9))
    ax.set(xlabel="Column",ylabel="Row")
    fig.tight_layout()
    fig.savefig(figures/"board.png")
    plt.close(fig)
    print(json.dumps(audit_result))


if __name__ == "__main__":
    main()
